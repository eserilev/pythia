"""Emit `SpecLean/Validation/Codecs.lean`: one `Codec dec_X enc_X` theorem per SSZ class of the
readable Lean (SPEC 9.2, `hash_tree_root` as an oracle).

Run from this repository, after the translator has written `SpecLean/Gen/Readable.lean`:

    python3 tools/gen_codec.py

The script reads the decoders of `Readable.lean`. A uint or byte vector alias gets `codec_uint` or
`codec_bytes`. A container gets a proof from `cont_ok` and `cont_good` (`HtrCodec.lean`), with the
codec of each field: `dec_Y` gives `codec_Y`, `decBooleanV` gives `codec_boolean`, and
`decListT k e l D` gives `codec_list k e l` of the codec of `D`.
"""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
READABLE = ROOT / "SpecLean" / "Gen" / "Readable.lean"
OUT = ROOT / "SpecLean" / "Validation" / "Codecs.lean"

ALIAS = re.compile(r"^abbrev dec_(\w+) : Dec \S+ := (decUintT|decBytesT) ")
CONT = re.compile(r"^def dec_(\w+) : Dec \S+ := fun h v => do$")
FIELD = re.compile(r"^  let \S+ ← fs\[(\d+)\]\? >>= (.*) h$")


def codec_of(dec: str) -> str:
    """The codec term for a decoder term."""
    out = re.sub(r"\bdec_(\w+)", r"codec_\1", dec)
    out = out.replace("decListT", "codec_list").replace("decBooleanV", "codec_boolean")
    return out


def container_proof(name: str, codecs: list[str]) -> str:
    n = len(codecs)
    ws = ", ".join(f"w{i}" for i in range(n))
    ok_list = ", ".join(f"fun h0 => ({c}).ok _ h0" for c in codecs)
    good_list = ", ".join(
        f"fun h0 => ({c}).good h w{i} x{i} hd{i} (shaped_item (i := {i}) hs ho rfl) h0"
        for i, c in enumerate(codecs))
    cons = " :: ".join(f"w{i}" for i in range(n)) + " :: []"
    steps = "\n".join(f"    obtain ⟨x{i}, hd{i}, hd⟩ := obind_some hd" for i in range(n))
    return f"""theorem codec_{name} : Codec dec_{name} enc_{name} where
  ok x h0 := by
    refine cont_ok' _ _ ?_ h0
    exact ⟨{ok_list}, trivial⟩
  good h v x hd hs h0 := by
    unfold dec_{name} at hd
    obtain ⟨fs, hc, hd⟩ := obind_some hd
    obtain ⟨a, rfl, ho⟩ := containerFieldsT_some hc
    have hl : fs.length = {n} := by rw [hs [] a _ fs _ rfl ho rfl]; rfl
    obtain ⟨{ws}, rfl⟩ : ∃ {' '.join(f'w{i}' for i in range(n))}, fs = {cons} := by
      match fs, hl with
      | {cons}, _ => exact ⟨{ws}, rfl⟩
{steps}
    obtain rfl := Option.some.inj hd
    refine cont_good' ho _ ?_ ?_ h0
    · exact ⟨{ok_list}, trivial⟩
    · exact ⟨{good_list}, trivial⟩
"""


def main():
    lines = READABLE.read_text().splitlines()
    out = []
    count = {"alias": 0, "container": 0}
    i = 0
    while i < len(lines):
        line = lines[i]
        m = ALIAS.match(line)
        if m:
            kind = "codec_uint" if m.group(2) == "decUintT" else "codec_bytes"
            out.append(f"theorem codec_{m.group(1)} : Codec dec_{m.group(1)} enc_{m.group(1)} :=\n"
                       f"  {kind} _\n")
            count["alias"] += 1
        m = CONT.match(line)
        if m and lines[i + 1].startswith("  let fs ← containerFieldsT"):
            name = m.group(1)
            codecs = []
            j = i + 2
            while lines[j].startswith("  let "):
                f = FIELD.match(lines[j])
                assert f and int(f.group(1)) == len(codecs), lines[j]
                codecs.append(codec_of(f.group(2)))
                j += 1
            out.append(container_proof(name, codecs))
            count["container"] += 1
            i = j
        i += 1
    header = f"""-- Generated by tools/gen_codec.py. Do not edit.
import SpecLean.Validation.HtrCodec

/-!
# A codec for every SSZ class

Generated by `tools/gen_codec.py` from the decoders of `Readable.lean`: {count['alias']} uint and
byte vector classes and {count['container']} containers. Each theorem says that a decoded heap value
has the content of the encoding of its readable value (`Codec`), so `htr_codec` links the
`hash_tree_root` oracle of the interpreter and of the readable Lean for that class.
-/

namespace SpecLean.Validation.HtrBridge

open SpecLean SpecLean.Rd SpecLean.Rd.Gen

set_option maxHeartbeats 4000000
set_option maxRecDepth 8192

"""
    OUT.write_text(header + "\n".join(out) + "\nend SpecLean.Validation.HtrBridge\n")
    print(f"{count['alias']} aliases, {count['container']} containers -> {OUT}")


if __name__ == "__main__":
    main()
