"""Construct tests: CPython against the Lean interpreter.

Run from the consensus-specs checkout, in its uv environment:

    cd ../consensus-specs-safe
    uv run python ../consensus-specs-lean/tools/constructs.py

The script serializes `Tests/constructs.py` (each `t_*` function and its callees, with the
pyspec module as namespace), runs each `t_*` function in CPython and in the interpreter, renders
both results in one canonical form, and compares them. It exits with status 1 on a difference.
"""

import ast
import dataclasses
import subprocess
import sys
from pathlib import Path

import pydantic
from eth_consensus_specs.gloas import minimal as spec
from ssz.bitfields import BitList, BitVector, ProgressiveBitList
from ssz.boolean import Boolean
from ssz.collections import _SSZSequence
from ssz.container import Container, ProgressiveContainer
from ssz.exceptions import SSZTypeError, SSZValueError
from ssz.uint import BaseUint

LEAN_DIR = Path(__file__).resolve().parent.parent
TESTS = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else LEAN_DIR / "Tests" / "constructs.py"


def tag(e: Exception) -> str:
    if isinstance(e, SSZValueError):
        return "sszValue"
    if isinstance(e, pydantic.ValidationError):
        return "validation"
    if isinstance(e, IndexError):
        return "indexError"
    if isinstance(e, KeyError):
        return "keyError"
    if isinstance(e, ZeroDivisionError):
        return "divisionByZero"
    if isinstance(e, (SSZTypeError, TypeError)):
        return "typeError"
    if isinstance(e, AssertionError):
        return "assertionFailed"
    if isinstance(e, ValueError):
        return "valueError"
    raise e


def py_bool(b) -> str:
    return "True" if b else "False"


def render(v) -> str:
    if isinstance(v, Boolean):
        return f"Boolean:{py_bool(v)}"
    if type(v) is bool:
        return f"bool:{py_bool(v)}"
    if isinstance(v, BaseUint):
        return f"{type(v).__name__}:{int(v)}"
    if type(v) is int:
        return f"int:{v}"
    if type(v) is str:
        return f"str:{v}"
    if v is None:
        return "None"
    if isinstance(v, bytes):
        return f"{type(v).__name__}:{v.hex()}"
    if isinstance(v, tuple):
        return "(" + ",".join(render(x) for x in v) + ")"
    if isinstance(v, (list, _SSZSequence, BitVector, BitList, ProgressiveBitList)):
        return "[" + ",".join(render(x) for x in v) + "]"
    if isinstance(v, (Container, ProgressiveContainer)):
        fields = ",".join(f"{f}={render(getattr(v, f))}" for f, _ in type(v)._FIELD_TYPES)
        return type(v).__name__ + "{" + fields + "}"
    if dataclasses.is_dataclass(v):
        fields = ",".join(f"{f.name}={render(getattr(v, f.name))}" for f in dataclasses.fields(v))
        return type(v).__name__ + "{" + fields + "}"
    if isinstance(v, set):
        return "set{" + ",".join(sorted(render(x) for x in v)) + "}"
    if isinstance(v, dict):
        return "{" + ",".join(f"{render(k)}:{render(x)}" for k, x in v.items()) + "}"
    return f"<{type(v).__name__}>"


def main():
    src = TESTS.read_text()
    names = [n.name for n in ast.parse(src).body
             if isinstance(n, ast.FunctionDef) and n.name.startswith("t_")]
    ns = dict(vars(spec))
    exec(compile(src, str(TESTS), "exec"), ns)
    expected = {}
    for n in names:
        try:
            expected[n] = "ok " + render(ns[n]())
        except Exception as e:  # noqa: BLE001
            expected[n] = "err " + tag(e)

    gen = LEAN_DIR / "Tests" / "Gen" / "Constructs.lean"
    subprocess.run([sys.executable, str(LEAN_DIR / "tools" / "serialize.py"), "--roots", "",
                    "--extra", str(TESTS), "--namespace", "Constructs", "--out", str(gen)],
                   check=True)
    main_lean = LEAN_DIR / "Tests" / "ConstructsMain.lean"
    calls = "\n".join(f'  runCase names (env testOracle) 100000 "{n}" Id.«{n}»' for n in names)
    main_lean.write_text(
        "-- Generated by tools/constructs.py. Do not edit.\n"
        "import Tests.Gen.Constructs\nimport Tests.Render\n\n"
        "open SpecLean SpecLean.Tests SpecLean.Constructs\n\n"
        f"def main : IO Unit := do\n{calls}\n")
    subprocess.run(["lake", "build", "Tests"], cwd=LEAN_DIR, check=True, capture_output=True)
    res = subprocess.run(["lake", "env", "lean", "--run", str(main_lean)], cwd=LEAN_DIR,
                         capture_output=True, text=True)
    if res.returncode != 0:
        sys.exit(res.stdout + res.stderr)
    got = dict(line.split(": ", 1) for line in res.stdout.splitlines() if ": " in line)
    bad = 0
    for n in names:
        line = got.get(n, "<missing>")
        same = line == expected[n]
        bad += not same
        print(f"{'same' if same else 'DIFF'} {n}: {line}" +
              ("" if same else f"\n       pyspec: {expected[n]}"))
    print(f"{len(names)} constructs, {bad} differences")
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
