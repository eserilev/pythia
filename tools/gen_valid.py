"""Generate the validation theorems (SPEC 9.2) of the readable Lean and keep the ones that the
tactic proves.

Run from the consensus-specs checkout, in its uv environment:

    cd ../consensus-specs-safe
    uv run python ../consensus-specs-lean/tools/gen_valid.py --tier leaves

It writes one candidate theorem per function of the tier, checks each with `lake env lean` in
parallel, each in a memory cap of `MEM`, and writes the proved ones to `SpecLean/Validation/Gen/<Tier>.lean`. It prints the
count and the reason of each failure.
"""

import argparse
import ast
import concurrent.futures
import json
import re
import os
import subprocess
import sys
import tempfile
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import rd_emit  # noqa: E402
import rd_fn  # noqa: E402
import rd_types as T  # noqa: E402
import serialize as S  # noqa: E402
import translate  # noqa: E402

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent

HEADER = """import SpecLean.Validation.Gen.Local
"""

# The calls tier: the first round uses the leaves, a later round also the calls proved so far.
CALLS_HEADER = """import SpecLean.Validation.Gen.Leaves
"""

CALLS_NEXT_HEADER = """import SpecLean.Validation.Gen.Calls
"""

LOCAL_HEADER = """-- Generated by tools/gen_valid.py. Do not edit.
import SpecLean.Gen.Readable
import SpecLean.Validation.Tactic
import SpecLean.Validation.Steps
import SpecLean.Validation.Decode
import SpecLean.Validation.Local

/-!
# Decoders of the items of state lists read only what they reach

The proofs of writes need these: a write elsewhere leaves a list item decoding the same.
-/

namespace SpecLean.Validation.Gen

open SpecLean SpecLean.Rd SpecLean.Rd.Gen SpecLean.Validation.Local SpecLean.Validation.Decode

"""

PRELUDE = """
namespace SpecLean.Validation.Gen

open SpecLean SpecLean.Rd SpecLean.Rd.Gen SpecLean.Encode SpecLean.Validation.Tactic
open SpecLean.Validation.Steps

variable (sha : Oracle) [Spec]

attribute [local instance] Cfg.default

set_option linter.unusedSectionVars false
set_option linter.unusedSimpArgs false

-- `whnf` of a result would evaluate a range check on a literal in unary.
attribute [local irreducible] ResultMatches
"""

FOOTER = "\nend SpecLean.Validation.Gen\n"


class Unsupported(Exception):
    pass


def classify(fns):
    """`loops`, `whiles` and the spec callees of each function."""
    out = {}
    for n, t in fns.items():
        loops = any(isinstance(x, (ast.For, ast.While, ast.comprehension)) for x in ast.walk(t))
        whiles = any(isinstance(x, ast.While) for x in ast.walk(t))
        calls = sorted(c for c in S.free_names(t) if c in fns and c != n)
        out[n] = dict(loops=loops, whiles=whiles, calls=calls)
    return out


class Gen:
    def __init__(self, b, em):
        self.b, self.em, self.n = b, em, b.names

    def decs_of(self, c, acc):
        """The decoders that unfold a container of class `c` and its nested containers."""
        n = self.n
        name = f"dec_{n.cls(c)}"
        if name in acc:
            return
        acc.append(name)
        fields = (list(c._FIELD_TYPES) if T.is_container_cls(c) else self.b.dataclass_fields[c])
        for _, ft in fields:
            if T.is_uint_cls(ft) or T.is_bytesn_cls(ft):
                d = f"dec_{n.cls(ft)}"
                if d not in acc:
                    acc.append(d)
            elif T.is_container_cls(ft):
                self.decs_of(ft, acc)

    def arg(self, j, t):
        """The binder, the interpreter value and the readable value of argument `j`."""
        x = f"x{j}"
        k = t[0]
        if k == "container":
            c = self.n.cls(t[1])
            return (f"(r{j} : Nat) ({x} : {c}) (hy{j} : dec_{c} h (.ref r{j}) = some {x})",
                    f"(.ref r{j})", x, f"r{j} {x} hy{j}")
        if k == "uint":
            ty = translate.uint_ty_term(self.n, t[1])
            return f"({x} : Nat)", f"(.uint {ty} {x})", f"(⟨{x}⟩ : {self.n.cls(t[1])})", x
        if k == "bytesN":
            return (f"({x} : List UInt8)", f"(.bytes Scope.Id.«{self.n.scope(t[1])}» {x})",
                    f"(⟨{x}⟩ : {self.n.cls(t[1])})", x)
        if k == "bool":
            return f"({x} : Bool)", f"(.bool {x})", x, x
        if k == "int":
            return f"({x} : Int)", f"(.int {x})", x, x
        if k == "boolean":
            return f"({x} : Bool)", f"(.boolean {x})", f"(⟨{x}⟩ : Boolean)", x
        if k == "bytes":
            return f"({x} : List UInt8)", f"(.bytes 0 {x})", x, x
        raise Unsupported(f"argument type {k}")

    def expect(self, t, rv="r"):
        """The relation of the return value `v` to the readable value `rv`, and simp names."""
        k = t[0]
        if k in ("uint", "bytesN"):
            c = self.n.cls(t[1])
            return f"v = (enc_{c} {rv} h').1", [f"enc_{c}", "encUint", "encBytesN"]
        if k == "bool":
            return f"v = .bool {rv}", []
        if k == "int":
            return f"v = .int {rv}", []
        if k == "boolean":
            return f"v = .boolean ({rv}).val", []
        if k == "bytes":
            return f"v = .bytes 0 {rv}", []
        if k == "none":
            return "v = .none", []
        raise Unsupported(f"return type {k}")

    def fpat(self, c, steps):
        """The `FPat` of a footprint pattern rooted at class `c`."""
        out, cur = [], c
        for st in steps:
            if st == "*":
                li = T.list_info(cur)
                if li is None:
                    raise Unsupported(f"pattern step * on {cur}")
                out.append(".any")
                cur = li[1]
            else:
                if not T.is_container_cls(cur):
                    raise Unsupported(f"pattern step {st} on {cur}")
                fields = [f for f, _ in cur._FIELD_TYPES]
                out.append(f".exact {fields.index(st)}")
                cur = dict(cur._FIELD_TYPES)[st]
        return f"⟨Scope.Id.«{self.n.scope(c)}», [{', '.join(out)}]⟩"

    def footprint(self, name, sig):
        pats = []
        for j, steps in self.per_fn.get(name, []):
            t = sig.params[j][1]
            if t[0] != "container":
                raise Unsupported(f"footprint root {t}")
            p = self.fpat(t[1], steps)
            if p not in pats:
                pats.append(p)
        return "[" + ", ".join(pats) + "]"

    def theorem(self, name, sig, tree, callees=(), fuel=64, poly=None):
        """The `_run` theorem at fuel `k + fuel` and the `_valid` theorem of SPEC 9.2. A call to
        a callee in `callees` uses the callee's `_run` theorem (`rd_call`).

        `poly = j`: the uint argument `j` has any class of its width, and the result has that
        class. Python keeps the class of an argument through arithmetic, so a caller can pass a
        `Gwei` to a `Uint64` parameter and get a `Gwei` back (`saturating_sub`)."""
        if any(t[0] in ("tvar", "utvar") for _, t in sig.params):
            raise Unsupported("generic")
        if any(sig.params[j][1][0] != "container" for j in sig.mutated):
            raise Unsupported("mutates a list argument")
        args = [self.arg(j, t) for j, (_, t) in enumerate(sig.params)]
        if poly is not None:
            t = sig.params[poly][1]
            if t[0] != "uint" or sig.ret[0] != "uint" or sig.mutated:
                raise Unsupported("poly")
            w = re.findall(r"\d+", translate.uint_ty_term(self.n, t[1]))[-1]
            x = f"x{poly}"
            args[poly] = (f"(t{poly} : UintTy) (ht{poly} : t{poly}.bits = {w}) ({x} : Nat)",
                          f"(.uint t{poly} {x})", args[poly][2], f"t{poly} ht{poly} {x}")
        ret = sig.ret
        outs = rd_fn.out_types(sig)
        rt = ("Unit" if not outs else self.em.lean_param(outs[0]) if len(outs) == 1 else
              "(" + " × ".join(self.em.lean_param(t) for t in outs) + ")")
        if poly is not None:
            exp = f"v = .uint t{poly} (UintC.val r) ∧ h' = h"
            encs = []
            name_run, name_valid = f"{name}_p{poly}_run", f"{name}_p{poly}_valid"
        elif not sig.mutated:
            e, encs = self.expect(ret)
            exp = f"{e} ∧ h' = h"
        else:
            k0 = 1 if ret != T.NONE else 0
            e, encs = self.expect(ret, rd_fn.Fn.proj(None, "r", 0, len(outs)) if k0 else "r")
            parts = [e]
            for i, j in enumerate(sig.mutated):
                c = self.n.cls(sig.params[j][1][1])
                rv = rd_fn.Fn.proj(None, "r", k0 + i, len(outs))
                parts.append(f"dec_{c} h' (.ref r{j}) = some {rv}")
            exp = " ∧ ".join(parts)
        fp = self.footprint(name, sig) if sig.mutated else "[]"
        binders = " ".join(a[0] for a in args)
        decs, hys = [], []
        for j, (_, t) in enumerate(sig.params):
            if t[0] == "container":
                self.decs_of(t[1], decs)
                hys.append(f"hy{j}")
        inv = ""
        if hys and callees:
            # The callees need the decode facts of the arguments: keep a copy of each.
            inv += "".join(f"  have {y}c := {y}\n" for y in hys)
        if hys:
            inv += (f"  simp only [rd_dec, Option.bind_eq_bind, Option.bind_eq_some_iff, "
                   f"rd_simp, Option.pure_def, Option.some.injEq, Value.ref.injEq, exists_eq_left', "
                   f"exists_eq_right] at {' '.join(hys)}\n  rd_split_hyps\n")
        vs = "[" + ", ".join(a[1] for a in args) + "]"
        rargs = " ".join(a[2] for a in args)
        hw = (f" (hw : WTree h {vs} {fp}) (hwf : HeapWF h) (haw : ArgsWF h {vs})"
              if sig.mutated else "")
        free = S.free_names(tree)
        consts = [T.ident(c) for c in sorted(free) if c in self.b.consts]
        cfg = sorted({n.attr for n in ast.walk(tree) if isinstance(n, ast.Attribute) and
                      isinstance(n.value, ast.Name) and n.value.id == "config"} |
                     {c for c in free if c in self.b.config_vars})
        defs = ([f"Scope.fn_{name}", T.ident(name), "Scope.env", "Scope.knownNames"] + consts + [f"Cfg.{c}" for c in cfg] +
                (["Cfg.default"] if cfg else []) + encs)
        fname = T.ident(name)
        # A class-polymorphic argument: one proof for each of the two kinds of class.
        split = (f"  rcases t{poly} with _ | ⟨_, _⟩ <;> simp only [UintTy.bits] at ht{poly} <;> "
                 f"subst ht{poly}\n" if poly is not None else "")
        if poly is None:
            name_run, name_valid = f"{name}_run", f"{name}_valid"
        names = " ".join(a[3] for a in args) + (" hw hwf haw" if sig.mutated else "")
        step = (f"(first | rd_call [{', '.join(c + '_run' for c in callees)}] | "
                f"(rd_split <;> (try rd_step)))" if callees else "(rd_split <;> (try rd_step))")
        return f"""
set_option maxHeartbeats 4000000 in
theorem {name_run} (gfp : Footprint) (h : Heap) {binders}{hw} (k : Nat) :
      ResultMatches gfp {fp} h {vs} (fun (r : {rt}) h' v => {exp})
        (interp (Scope.env sha) (k + {fuel}) Scope.Id.«{name}» {vs} h)
        ({fname} {rargs}) := by
{inv}{split}  all_goals (
  rw [interp, callName, callValue.eq_def]
  simp [rd_simp, lookup_lit, unfold_known, fieldIndex_lit, stop_call, stop_call_post, {", ".join(defs)}{", *" if hys else ""}]
  rd_step
  repeat' {step}
  all_goals (first | rd_finish | ((try rd_heap); rd_frame; done)))

theorem {name_valid} (gfp : Footprint) (h : Heap) {binders}{hw} :
    ∃ N, ∀ fuel ≥ N,
      ResultMatches gfp {fp} h {vs} (fun (r : {rt}) h' v => {exp})
        (interp (Scope.env sha) fuel Scope.Id.«{name}» {vs} h)
        ({fname} {rargs}) :=
  ⟨{fuel}, fun fuel hf => by
    obtain ⟨k, rfl⟩ := Nat.exists_eq_add_of_le' hf
    exact {name_run} sha gfp h {names} k⟩
"""


MEM = "4G"


def check(name, text, workdir, header):
    """Compile one candidate. Returns (name, ok, seconds, first error line)."""
    f = Path(workdir) / f"{name}.lean"
    f.write_text(header + PRELUDE + text + FOOTER)
    t0 = time.time()
    try:
        # Each check runs in its own memory cap: a proof term that blows up must fail, not
        # take the machine down.
        r = subprocess.run(["systemd-run", "--user", "--scope", "-q", "-p", f"MemoryMax={MEM}",
                            "-p", "MemorySwapMax=0", "lake", "env", "lean", str(f)], cwd=ROOT,
                           capture_output=True, text=True, timeout=600)
        out = r.stdout + r.stderr
        ok = r.returncode == 0 and "error" not in out and "sorry" not in out
    except subprocess.TimeoutExpired:
        out, ok = "timeout", False
    err = next((ln.split(".lean:", 1)[-1] for ln in out.splitlines() if "error" in ln), out[:200])
    return name, ok, time.time() - t0, err


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--rev", default="889a389f9")
    ap.add_argument("--preset", default="minimal")
    ap.add_argument("--tier", default="leaves", choices=["leaves", "calls"])
    ap.add_argument("--only", default=None)
    ap.add_argument("--jobs", type=int, default=2)
    ap.add_argument("--out", default=None)
    args = ap.parse_args()
    commit, spec_object, sources, spec, fns, sources_text, _ = S.load_scope(
        args.rev, "gloas", args.preset, translate.scope_roots())
    names = T.Names(spec)
    b = translate.Build(spec, fns, names)
    b.sources, b.sources_text, b.config_vars = sources, sources_text, spec_object.config_vars
    em = rd_emit.Emitter(b)
    em.collect()
    em.emit_constants()
    em.emit_config()
    em.build_sigs()
    cls = classify(fns)
    gen_dir = ROOT / "SpecLean/Validation/Gen"
    if args.tier == "leaves":
        tier = sorted(n for n, c in cls.items() if not c["loops"] and not c["calls"])
    else:
        # Functions with calls and no loops. A round checks the ones whose callees all have a
        # theorem; the next round can use the theorems of this one.
        tier = sorted(n for n, c in cls.items() if not c["loops"] and c["calls"])
        have = set(re.findall(r"^theorem (\w+)_run ", (gen_dir / "Leaves.lean").read_text(),
                              re.M))
    if args.only:
        tier = [n for n in tier if n in args.only.split(",")]
    g = Gen(b, em)
    from footprint import footprint
    ssz_names = {x for x in dir(spec) if isinstance(getattr(spec, x), type)
                 and T.of_class(getattr(spec, x)) is not None}
    _, _, g.per_fn = footprint(b.fns, ssz_names, lambda t, st: True)
    # The list item classes of the state, and the classes that they hold.
    items = []

    def add_item(c):
        if not T.is_container_cls(c) or c in items:
            return
        for _, ft in c._FIELD_TYPES:
            add_item(ft)
            li = T.list_info(ft)
            if li:
                add_item(li[1])
        items.append(c)
    for c in b.order:
        if T.is_container_cls(c):
            for _, ft in c._FIELD_TYPES:
                li = T.list_info(ft)
                if li and T.is_container_cls(li[1]):
                    add_item(li[1])
    local = LOCAL_HEADER + "".join(
        f"instance : LocalDec dec_{names.cls(c)} := by rd_local dec_{names.cls(c)}\n"
        for c in items) + "\nend SpecLean.Validation.Gen\n"
    lp = ROOT / "SpecLean/Validation/Gen/Local.lean"
    lp.parent.mkdir(parents=True, exist_ok=True)
    if not lp.exists() or lp.read_text() != local:
        lp.write_text(local)
    global PRELUDE
    decs_all = [f"dec_{names.cls(c)}" for c in b.order
                if T.is_uint_cls(c) or T.is_bytesn_cls(c) or T.is_container_cls(c)]
    PRELUDE += "\nattribute [local rd_dec] " + " ".join(decs_all) + "\n"
    # The scalar encoders: a callee's result value is one, and the caller computes with it.
    encs_all = [f"enc_{names.cls(c)}" for c in b.order if T.is_uint_cls(c) or T.is_bytesn_cls(c)]
    PRELUDE += ("\nattribute [local rd_simp] encUint encBytesN encBoolean " + " ".join(encs_all) +
                "\n")
    base = ("SpecLean.Validation.Gen.Local" if args.tier == "leaves" else
            "SpecLean.Validation.Gen.Leaves")
    r = subprocess.run(["systemd-run", "--user", "--scope", "-q", "-p", "MemoryMax=8G", "-p",
                        "MemorySwapMax=0", "lake", "build", base], cwd=ROOT,
                       capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit("lake build failed:\n" + r.stdout[-3000:])
    work = tempfile.mkdtemp(prefix="gen-valid-")
    out = Path(args.out) if args.out else gen_dir / (args.tier.capitalize() + ".lean")
    out.parent.mkdir(parents=True, exist_ok=True)
    proved, failed, skipped, secs, body = [], {}, {}, {}, ""

    def doc():
        return (f"\n/-!\n# Validation theorems: {args.tier}\n\nGenerated by tools/gen_valid.py. "
                f"Do not edit. The tactic proves {len(proved)} of the {len(tier)} functions of the "
                f"tier.\n-/\n")
    header = file_header = HEADER if args.tier == "leaves" else CALLS_HEADER
    fuel = {n: 64 for n in (have if args.tier == "calls" else ())}
    todo = list(tier)
    while todo:
        cands = {}
        for n in todo:
            callees = cls[n]["calls"]
            if args.tier == "calls" and not all(c in fuel for c in callees):
                continue
            f = 64 + max((fuel[c] for c in callees), default=0)
            # The theorems of each callee: the plain one and its class-polymorphic variants.
            lemmas = [k for c in callees for k in fuel if k == c or k.startswith(c + "_p")]
            try:
                cands[n] = (g.theorem(n, em.sigs[n], fns[n], lemmas, f), f)
            except (Unsupported, S.Unsupported, ValueError) as e:
                skipped[n] = f"no statement: {e}"
                continue
            sig = em.sigs[n]
            for j, (_, t) in enumerate(sig.params):
                if t[0] == "uint" and sig.ret[0] == "uint" and not sig.mutated:
                    try:
                        cands[f"{n}_p{j}"] = (g.theorem(n, sig, fns[n], lemmas, f, poly=j), f)
                    except (Unsupported, S.Unsupported, ValueError):
                        pass
        todo = [n for n in todo if n not in cands and n not in skipped]
        if not cands:
            break
        with concurrent.futures.ThreadPoolExecutor(args.jobs) as ex:
            results = list(ex.map(lambda kv: check(kv[0], kv[1][0], work, header),
                                  cands.items()))
        new = sorted(n for n, ok, _, _ in results if ok)
        failed.update({n: e for n, ok, _, e in results if not ok and n in tier})
        secs.update({n: round(t, 1) for n, _, t, _ in results})
        proved += [n for n in new if n in tier]
        body += "".join(cands[n][0] for n in new)
        for n in new:
            fuel[n] = cands[n][1]
        out.write_text(f"-- Generated by tools/gen_valid.py. Do not edit.\n{file_header}{doc()}"
                       f"{PRELUDE}{body}{FOOTER}")
        if args.tier == "leaves" or not new:
            break
        # The next round imports the theorems of this one.
        r = subprocess.run(["systemd-run", "--user", "--scope", "-q", "-p", "MemoryMax=8G", "-p",
                            "MemorySwapMax=0", "lake", "build", "SpecLean.Validation.Gen.Calls"],
                           cwd=ROOT, capture_output=True, text=True)
        if r.returncode != 0:
            sys.exit("lake build of the round failed:\n" + r.stdout[-3000:])
        header = CALLS_NEXT_HEADER
    for n in todo:
        skipped.setdefault(n, "a callee has no theorem")
    print(f"tier {args.tier}: {len(proved)}/{len(tier)} proved, wrote {out}")
    print(f"  class-polymorphic variants: {sorted(k for k in fuel if k not in tier and '_p' in k)}")
    for n in sorted(skipped):
        print(f"  SKIP {n}: {skipped[n]}")
    for n in sorted(failed):
        print(f"  FAIL {n} ({secs[n]}s): {failed[n][:160]}")
    for n in proved:
        print(f"  OK {n} ({secs[n]}s)")
    json.dump({"proved": proved, "failed": failed, "skipped": skipped, "secs": secs},
              open(Path(work) / "result.json", "w"), indent=1)
    print(f"candidates in {work}")


if __name__ == "__main__":
    main()
