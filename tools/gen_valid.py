def run_fuels(text):
    """The fuel of each `_run` theorem of a generated file, when it is a constant."""
    out = {}
    for m in re.finditer(r"^theorem (\w+)_run .*?\(interp \(Scope\.env sha\) \(k \+ ([^)]*)\)",
                         text, re.M | re.S):
        parts = [x.strip() for x in m[2].split("+")]
        if all(x.isdigit() for x in parts):
            out[m[1]] = sum(int(x) for x in parts)
    return out


def bound_fuels(text):
    """The fuel of each `_run` theorem whose fuel depends on its input: the constant and the
    list lengths `(j, field)` of the arguments (`field` is None for a list argument)."""
    out = {}
    for m in re.finditer(r"^theorem (\w+)_run .*?\(interp \(Scope\.env sha\) \(k \+ ([^)]*)\)",
                         text, re.M | re.S):
        parts = [x.strip() for x in m[2].split("+")]
        if all(x.isdigit() for x in parts):
            continue
        c, terms = 0, []
        for x in parts:
            if x.isdigit():
                c += int(x)
                continue
            mm = re.fullmatch(r"x(\d+)(?:\.(\S+))?\.length", x)
            if not mm:
                break
            terms.append((int(mm[1]), mm[2]))
        else:
            out[m[1]] = (c, terms)
    return out


def check(name, text, workdir, header):
    """Compile one candidate. Returns (name, ok, seconds, first error line)."""
    f = Path(workdir) / f"{name}.lean"
    f.write_text(header + PRELUDE + text + FOOTER)
    t0 = time.time()
    try:
        # Each check runs in its own memory cap: a proof term that blows up must fail, not
        # take the machine down.
        r = subprocess.run(["systemd-run", "--user", "--scope", "-q", "-p", f"MemoryMax={MEM}",
                            "-p", "MemorySwapMax=0", "lake", "env", "timeout", "600", "lean", str(f)],
                           cwd=ROOT, capture_output=True, text=True, timeout=660)
        out = r.stdout + r.stderr
        ok = r.returncode == 0 and "error" not in out and "sorry" not in out
    except subprocess.TimeoutExpired:
        out, ok = "timeout", False
    err = next((ln.split(".lean:", 1)[-1] for ln in out.splitlines() if "error" in ln), out[:200])
    return name, ok, time.time() - t0, err


