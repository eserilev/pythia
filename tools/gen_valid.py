class Unsupported(Exception):
    pass


def classify(fns):
    """`loops`, `whiles` and the spec callees of each function."""
    out = {}
    for n, t in fns.items():
        loops = any(isinstance(x, (ast.For, ast.While, ast.comprehension)) for x in ast.walk(t))
        whiles = any(isinstance(x, ast.While) for x in ast.walk(t))
        calls = sorted(c for c in S.free_names(t) if c in fns and c != n)
        out[n] = dict(loops=loops, whiles=whiles, calls=calls)
    return out


class Gen:
    def __init__(self, b, em):
        self.b, self.em, self.n = b, em, b.names

    def decs_of(self, c, acc):
        """The decoders that unfold a container of class `c` and its nested containers."""
        n = self.n
        name = f"dec_{n.cls(c)}"
        if name in acc:
            return
        acc.append(name)
        fields = (list(c._FIELD_TYPES) if T.is_container_cls(c) else self.b.dataclass_fields[c])
        for _, ft in fields:
            if T.is_uint_cls(ft) or T.is_bytesn_cls(ft):
                d = f"dec_{n.cls(ft)}"
                if d not in acc:
                    acc.append(d)
            elif T.is_container_cls(ft):
                self.decs_of(ft, acc)

    def arg(self, j, t):
        """The binder, the interpreter value and the readable value of argument `j`."""
        x = f"x{j}"
        k = t[0]
        if k == "container":
            c = self.n.cls(t[1])
            return (f"(r{j} : Nat) ({x} : {c}) (hy{j} : dec_{c} h (.ref r{j}) = some {x})",
                    f"(.ref r{j})", x, f"r{j} {x} hy{j}")
        if k == "uint":
            ty = translate.uint_ty_term(self.n, t[1])
            return f"({x} : Nat)", f"(.uint {ty} {x})", f"(⟨{x}⟩ : {self.n.cls(t[1])})", x
        if k == "bytesN":
            return (f"({x} : List UInt8)", f"(.bytes Scope.Id.«{self.n.scope(t[1])}» {x})",
                    f"(⟨{x}⟩ : {self.n.cls(t[1])})", x)
        if k == "bool":
            return f"({x} : Bool)", f"(.bool {x})", x, x
        if k == "int":
            return f"({x} : Int)", f"(.int {x})", x, x
        if k == "boolean":
            return f"({x} : Bool)", f"(.boolean {x})", f"(⟨{x}⟩ : Boolean)", x
        if k == "bytes":
            return f"({x} : List UInt8)", f"(.bytes 0 {x})", x, x
        if k == "list":
            # A list argument is an object of the heap, as a container is.
            d = self.em.dec_of(t)
            if d is None:
                raise Unsupported("argument type list")
            lt = self.em.lean_param(t)
            return (f"(r{j} : Nat) ({x} : {lt}) (hy{j} : {d} h (.ref r{j}) = some {x})",
                    f"(.ref r{j})", x, f"r{j} {x} hy{j}")
        raise Unsupported(f"argument type {k}")

    def expect(self, t, rv="r"):
        """The relation of the return value `v` to the readable value `rv`, and simp names."""
        k = t[0]
        if k == "uint":
            # The range too: a caller that stores the result decodes it again.
            c = self.n.cls(t[1])
            w = re.findall(r"\d+", translate.uint_ty_term(self.n, t[1]))[-1]
            return (f"v = (enc_{c} {rv} h').1 ∧ UintC.val {rv} < 2 ^ {w}",
                    [f"enc_{c}", "encUint", "encBytesN"])
        if k == "bytesN":
            # The length too, as the range of a uint.
            c = self.n.cls(t[1])
            return (f"v = (enc_{c} {rv} h').1 ∧ (BytesC.data {rv}).length = {t[1].LENGTH}",
                    [f"enc_{c}", "encUint", "encBytesN"])
        if k == "bool":
            return f"v = .bool {rv}", []
        if k == "int":
            return f"v = .int {rv}", []
        if k == "boolean":
            return f"v = .boolean ({rv}).val", []
        if k == "bytes":
            return f"v = .bytes 0 {rv}", []
        if k == "none":
            return "v = .none", []
        raise Unsupported(f"return type {k}")

    def fpat(self, c, steps):
        """The `FPat` of a footprint pattern rooted at class `c`."""
        out, cur = [], c
        for st in steps:
            if st == "*":
                li = T.list_info(cur)
                if li is None:
                    raise Unsupported(f"pattern step * on {cur}")
                out.append(".any")
                cur = li[1]
            else:
                if not T.is_container_cls(cur):
                    raise Unsupported(f"pattern step {st} on {cur}")
                fields = [f for f, _ in cur._FIELD_TYPES]
                out.append(f".exact {fields.index(st)}")
                cur = dict(cur._FIELD_TYPES)[st]
        return f"⟨Scope.Id.«{self.n.scope(c)}», [{', '.join(out)}]⟩"

    def footprint(self, name, sig):
        pats = []
        for j, steps in self.per_fn.get(name, []):
            t = sig.params[j][1]
            if t[0] != "container":
                raise Unsupported(f"footprint root {t}")
            p = self.fpat(t[1], steps)
            if p not in pats:
                pats.append(p)
        return "[" + ", ".join(pats) + "]"

    def own_slices(self, name, sig, tree):
        """The fields `root.f = root.f[lo:hi]` of a function, as field positions."""
        out = set()
        for st in ast.walk(tree):
            if not (isinstance(st, ast.Assign) and len(st.targets) == 1):
                continue
            t, v = st.targets[0], st.value
            if not (isinstance(t, ast.Attribute) and isinstance(t.value, ast.Name) and
                    isinstance(v, ast.Subscript) and isinstance(v.slice, ast.Slice) and
                    isinstance(v.value, ast.Attribute) and v.value.attr == t.attr and
                    isinstance(v.value.value, ast.Name) and v.value.value.id == t.value.id):
                continue
            for pn, pt in sig.params:
                if pn == t.value.id and pt[0] == "container":
                    fields = [f for f, _ in pt[1]._FIELD_TYPES]
                    if t.attr in fields:
                        out.add(fields.index(t.attr))
        return out

    def slices(self, name):
        """The slice fields of a function and of its callees: each needs a fact about the
        global footprint (SPEC 9.2, `NoNewPaths`)."""
        if name in self.slice_memo:
            return self.slice_memo[name]
        self.slice_memo[name] = set()
        out = set(self.own_slices(name, self.em.sigs[name], self.b.fns[name]))
        for c in self.cls[name]["calls"]:
            if c in self.em.sigs:
                out |= self.slices(c)
        self.slice_memo[name] = out
        return out

    def loop_defs(self, name):
        """The binders and the result type of each readable loop function of `name`."""
        out, k = [], 1
        while True:
            m = re.search(rf"^def {re.escape(T.ident(name))}\.loop{k} (.*?) : SpecM (.*?) :=(?: do)?$",
                          self.readable, re.M)
            if not m:
                return out
            out.append((re.findall(r"\(([^\s:()]+) : ([^()]+)\)", m.group(1)), m.group(2)))
            k += 1

    def loops(self, name, sig, tree, callees=(), fuel=64):
        """The theorem of each loop of a function (SPEC 9.3). The loop is at the top level of the
        body and keeps the heap. A `for` loop runs over a list field of the container argument.
        A `while` loop has a measure below `2 ^ 64`. Each iteration keeps the locals that the loop
        reads, and the locals that it writes hold the readable values. Returns the text, the
        theorem names, the fuel bound of each loop and the container argument."""
        c = self.cls[name]
        body = S.strip_docstring(tree.body)
        loops = [(p, s) for p, s in enumerate(body) if isinstance(s, (ast.For, ast.While))]
        if not loops:
            return "", [], [], None
        if sig.mutated or any(isinstance(x, ast.comprehension) for x in ast.walk(tree)):
            raise Unsupported("loop kind")
        if len(loops) != sum(isinstance(x, (ast.For, ast.While)) for x in ast.walk(tree)):
            raise Unsupported("nested loop")
        defs = self.loop_defs(name)
        if len(defs) != len(loops):
            raise Unsupported("loop functions")
        pnames = [pn for pn, _ in sig.params]
        conts = [j for j, (_, t) in enumerate(sig.params) if t[0] == "container"]
        if len(conts) > 1:
            raise Unsupported("loop: one container argument")
        jj = conts[0] if conts else None
        args = [self.arg(j, t) for j, (_, t) in enumerate(sig.params)]
        fname = T.ident(name)
        text, names, bounds = "", [], []
        for k, ((p, s), (binders, rty)) in enumerate(zip(loops, defs), 1):
            for x in ast.walk(s):
                if isinstance(x, (ast.Return, ast.Break, ast.Continue)):
                    raise Unsupported("loop exit")
            loop = f"{fname}.loop{k}"
            if isinstance(s, ast.For):
                it = s.iter
                if not (jj is not None and isinstance(it, ast.Attribute) and
                        isinstance(it.value, ast.Name) and it.value.id == pnames[jj] and
                        isinstance(s.target, ast.Name)):
                    raise Unsupported("loop source")
                fields = [f for f, _ in sig.params[jj][1][1]._FIELD_TYPES]
                ni = next(i for i, (b, ty) in enumerate(binders) if b == "i_")
                cap, carry = binders[:ni - 1], binders[ni + 1:]
            else:
                cap = [(b, ty) for b, ty in binders if not b.endswith("_in")]
                carry = binders[len(cap):]
            if any(b not in pnames for b, _ in cap) or not carry:
                raise Unsupported("loop: captured local")
            carried = []
            for b, ty in carry:
                cl = getattr(self.b.spec, ty, None)
                if cl is None or not T.is_uint_cls(cl) or not b.endswith("_in"):
                    raise Unsupported(f"loop: carried {ty}")
                ut = translate.uint_ty_term(self.n, cl)
                carried.append((b[:-3], ty, ut, re.findall(r"\d+", ut)[-1]))
            capj = [pnames.index(b) for b, _ in cap]
            for j in capj:
                if sig.params[j][1][0] not in ("container", "uint"):
                    raise Unsupported("loop: captured kind")
            rel = f"{name}_loop{k}_rel"
            relb = " ".join(f"(r{j} : Nat)" if j == jj else f"(x{j} : Nat)" for j in capj)
            rela = " ".join(f"r{j}" if j == jj else f"x{j}" for j in capj)
            n = len(carried)
            res = [rd_fn.Fn.proj(None, "acc", i, n) if n > 1 else "acc" for i in range(n)]
            accs = [f"acc{i}" for i in range(n)]

            def facts(L, vals):
                cf = [f"{L} Scope.Id.«{x}» = some (.uint {ut} ({a}).val)"
                      for (x, _, ut, _), a in zip(carried, vals)]
                cf += [f"({a}).val < 2 ^ {w}" for (_, _, _, w), a in zip(carried, vals)]
                pf = [f"{L} Scope.Id.«{pnames[j]}» = some {args[j][1]}" for j in capj]
                return pf + cf
            rty_rel = rty
            text += f"""
/-- An iteration of the loop {k} of `{name}`: the heap stays, and the locals hold the readable
values. -/
def {rel} (h : Heap) {relb} : Res (Outcome × Locals × Heap) → SpecM {rty_rel} → Prop
  | .ok (.normal, L', h'), .ok acc => h' = h ∧ {" ∧ ".join(facts("L'", res))}
  | .error e, .error f => e ≠ .outOfFuel ∧ e.fail = f
  | _, _ => False

attribute [local irreducible] {rel}
"""
            hl = [f"hL{i}" for i in range(len(facts("L", accs)))]
            bnd = " ".join(args[j][0] for j in sorted(set(capj) | ({jj} if jj is not None
                                                                     else set())))
            accb = " ".join(f"({a} : {ty})" for a, (_, ty, _, _) in zip(accs, carried))
            hy = f"hy{jj}"

            def dec(ind):
                if jj is None:
                    return (f"try simp only [{loop}.μ, rd_simp] at hn\n{ind}simp [rd_simp, "
                            f"lookup_lit, unfold_known, fieldIndex_lit, stop_call, stop_call_post, "
                            f"Scope.env, Scope.knownNames, {loop}.μ, *]")
                cp = f"have {hy}c := {hy}\n{ind}" if callees else ""
                return (cp + f"simp only [rd_dec, Option.bind_eq_bind, Option.bind_eq_some_iff, "
                        f"rd_simp, Option.pure_def, Option.some.injEq, Value.ref.injEq, "
                        f"exists_eq_left', exists_eq_right] at {hy}\n{ind}rd_split_keep x{jj}\n"
                        f"{ind}simp [rd_simp, lookup_lit, unfold_known, fieldIndex_lit, stop_call, "
                        f"stop_call_post, follow, Scope.env, Scope.knownNames, *]")
            rargs = " ".join(args[j][2] for j in capj)
            call = (f"rd_call [{', '.join(c + '_run' for c in callees)}] | " if callees else "")
            steps = f"""rd_step
      repeat' (first | rd_ih | {call}(rd_items; try rd_step) |
        (rd_split <;> (try rd_step) <;> (try simp only [{rel}] at ⊢)))
      all_goals (first | rd_finish | (simp only [{rel}]; simp [*]) | omega)"""
            head = f"""
set_option maxHeartbeats 4000000 in
set_option maxRecDepth 8192 in
theorem {name}_loop{k} (h : Heap) {bnd} (l : Nat)"""
            if isinstance(s, ast.For):
                ln = f"x{jj}.{T.ident(it.attr)}.length"
                bounds.append(ln)
                text += head + f""" (t : Target) (it : Expr) (body : List Stmt)
    (hfor : Scope.fn_{name}.body[{p}]? = some (.forStmt l t it body)) (src : IterSrc)
    (hsrc : ∀ i, iterItem h src i = .ok (follow h (.ref r{jj}) [{fields.index(it.attr)}, i])) :
    ∀ m i {accb} (L : Locals), {" → ".join(facts("L", accs))} → {ln} - i ≤ m →
      {rel} h {rela} (execFor (Scope.env sha) (m + {fuel}) L h t src i body)
        ({loop} {rargs} {ln} i {" ".join(accs)}) := by
  simp only [Scope.fn_{name}, List.getElem?_cons_succ, List.getElem?_cons_zero, Option.some.injEq,
    Stmt.forStmt.injEq] at hfor
  obtain ⟨rfl, rfl, rfl, rfl⟩ := hfor
  intro m
  induction m with
  | zero =>
    intro i {" ".join(accs)} L {" ".join(hl)} hn
    rw [execFor, {loop}, hsrc, dif_neg (show ¬ i < {ln} by omega)]
    {dec("    ")}
    simp (disch := omega) only [List.getElem?_eq_none]
    all_goals (simp only [{rel}]; simp [*])
  | succ m ih =>
    replace ih := Hide.mk ih
    intro i {" ".join(accs)} L {" ".join(hl)} hn
    rw [execFor, {loop}, hsrc]
    by_cases hi : i < {ln}
    · rw [dif_pos hi]
      {dec("      ")}
      {steps}
    · rw [dif_neg hi]
      {dec("      ")}
      all_goals (simp only [{rel}]; simp [*])
"""
            else:
                # Every measure is a uint or a difference of uints: below `2 ^ 64`.
                bounds.append("18446744073709551616")
                text += f"\nattribute [local simp] {loop}.μ\n" + head + f""" (c : Expr) (body : List Stmt)
    (hw : Scope.fn_{name}.body[{p}]? = some (.whileStmt l c body)) :
    ∀ m {accb} (L : Locals), {" → ".join(facts("L", accs))} →
      {loop}.μ {rargs} {" ".join(accs)} ≤ m →
      {rel} h {rela} (execWhile (Scope.env sha) (m + {fuel}) L h c body)
        ({loop} {rargs} {" ".join(accs)}) := by
  simp only [Scope.fn_{name}, List.getElem?_cons_succ, List.getElem?_cons_zero, Option.some.injEq,
    Stmt.whileStmt.injEq] at hw
  obtain ⟨rfl, rfl, rfl⟩ := hw
  intro m
  induction m with
  | zero =>
    intro {" ".join(accs)} L {" ".join(hl)} hn
    rw [execWhile, {loop}]
    {dec("    ")}
    all_goals (
      {steps})
  | succ m ih =>
    replace ih := Hide.mk ih
    intro {" ".join(accs)} L {" ".join(hl)} hn
    rw [execWhile, {loop}]
    {dec("    ")}
    all_goals (
      {steps})
"""
            names.append(f"{name}_loop{k}")
        return text, names, bounds, jj

    def theorem(self, name, sig, tree, callees=(), fuel=64, poly=None, tie=False):
        """The `_run` theorem at fuel `k + fuel` and the `_valid` theorem of SPEC 9.2. A call to
        a callee in `callees` uses the callee's `_run` theorem (`rd_call`).

        `poly = j`: the uint argument `j` has any class of its width, and the result has that
        class. Python keeps the class of an argument through arithmetic, so a caller can pass a
        `Gwei` to a `Uint64` parameter and get a `Gwei` back (`saturating_sub`)."""
        if any(t[0] in ("tvar", "utvar") for _, t in sig.params):
            raise Unsupported("generic")
        if any(sig.params[j][1][0] != "container" for j in sig.mutated):
            raise Unsupported("mutates a list argument")
        args = [self.arg(j, t) for j, (_, t) in enumerate(sig.params)]
        if poly is not None:
            t = sig.params[poly][1]
            if t[0] != "uint" or sig.ret[0] != "uint" or sig.mutated:
                raise Unsupported("poly")
            w = re.findall(r"\d+", translate.uint_ty_term(self.n, t[1]))[-1]
            x = f"x{poly}"
            args[poly] = (f"(t{poly} : UintTy) (ht{poly} : t{poly}.bits = {w}) ({x} : Nat)",
                          f"(.uint t{poly} {x})", args[poly][2], f"t{poly} ht{poly} {x}")
            if tie:
                # Each `int` parameter gets a uint of the same class, as `delta: Gwei` passed to
                # `b: int` in `saturating_sub(balance, delta)`.
                ints = [j for j, (_, t) in enumerate(sig.params) if t[0] == "int"]
                if not ints:
                    raise Unsupported("tie")
                for j in ints:
                    y = f"x{j}"
                    args[j] = (f"({y} : Nat)", f"(.uint t{poly} {y})", f"({y} : Int)", y)
        ret = sig.ret
        outs = rd_fn.out_types(sig)
        rt = ("Unit" if not outs else self.em.lean_param(outs[0]) if len(outs) == 1 else
              "(" + " × ".join(self.em.lean_param(t) for t in outs) + ")")
        if poly is not None:
            exp = f"v = .uint t{poly} (UintC.val r) ∧ UintC.val r < 2 ^ {w} ∧ h' = h"
            encs = []
            sfx = f"_p{poly}" + ("i" if tie else "")
            name_run, name_valid = f"{name}{sfx}_run", f"{name}{sfx}_valid"
        elif not sig.mutated:
            e, encs = self.expect(ret)
            exp = f"{e} ∧ h' = h"
        else:
            k0 = 1 if ret != T.NONE else 0
            e, encs = self.expect(ret, rd_fn.Fn.proj(None, "r", 0, len(outs)) if k0 else "r")
            parts = [e]
            for i, j in enumerate(sig.mutated):
                c = self.n.cls(sig.params[j][1][1])
                rv = rd_fn.Fn.proj(None, "r", k0 + i, len(outs))
                parts.append(f"dec_{c} h' (.ref r{j}) = some {rv}")
            exp = " ∧ ".join(parts)
        fp = self.footprint(name, sig) if sig.mutated else "[]"
        ltext, lnames, lens, jj = (self.loops(name, sig, tree, callees, fuel) if poly is None else
                                   ("", [], [], None))
        if lnames:
            # Each iteration of a loop costs one unit of fuel.
            # The literal stays last: the interpreter's equations match `n + 1`.
            fuel = f"{' + '.join(lens)} + {fuel + 64}"
        binders = " ".join(a[0] for a in args)
        decs, hys = [], []
        for j, (_, t) in enumerate(sig.params):
            if t[0] == "container":
                self.decs_of(t[1], decs)
                hys.append(f"hy{j}")
            elif t[0] == "list":
                hys.append(f"hy{j}")
        inv = ""
        if hys and (callees or lnames):
            # The callees need the decode facts of the arguments: keep a copy of each.
            inv += "".join(f"  have {y}c := {y}\n" for y in hys)
        if hys:
            inv += (f"  simp only [rd_dec, Option.bind_eq_bind, Option.bind_eq_some_iff, "
                   f"rd_simp, Option.pure_def, Option.some.injEq, Value.ref.injEq, exists_eq_left', "
                   f"exists_eq_right] at {' '.join(hys)}\n  " +
                    (f"rd_split_keep x{jj}\n" if lnames and jj is not None else "rd_split_hyps\n"))
        vs = "[" + ", ".join(a[1] for a in args) + "]"
        rargs = " ".join(a[2] for a in args)
        hw = (f" (hw : WTree h {vs} {fp}) (hwf : HeapWF h) (haw : ArgsWF h {vs})"
              if sig.mutated else "")
        sl = sorted(self.slices(name))
        hw += "".join(f" (hgfp{f} : ∀ pat ∈ gfp, ∀ j j' rest, Matches pat.steps ({f} :: j :: rest) → "
                      f"Matches pat.steps ({f} :: j' :: rest))" for f in sl)
        free = S.free_names(tree)
        consts = [T.ident(c) for c in sorted(free) if c in self.b.consts]
        cfg = sorted({n.attr for n in ast.walk(tree) if isinstance(n, ast.Attribute) and
                      isinstance(n.value, ast.Name) and n.value.id == "config"} |
                     {c for c in free if c in self.b.config_vars})
        defs = ([f"Scope.fn_{name}", T.ident(name), "Scope.env", "Scope.knownNames"] + consts + [f"Cfg.{c}" for c in cfg] +
                (["Cfg.default"] if cfg else []) + encs)
        fname = T.ident(name)
        # A class-polymorphic argument: one proof for each of the two kinds of class.
        split = (f"  rcases t{poly} with _ | ⟨_, _⟩ <;> simp only [UintTy.bits] at ht{poly} <;> "
                 f"subst ht{poly}\n" if poly is not None else "")
        if poly is None:
            name_run, name_valid = f"{name}_run", f"{name}_valid"
        names = (" ".join(a[3] for a in args) + (" hw hwf haw" if sig.mutated else "") +
                 "".join(f" hgfp{f}" for f in sl))
        alts = ([f"rd_loop [{', '.join(lnames)}]"] if lnames else []) + (
            [f"rd_call [{', '.join(c + '_run' for c in callees)}]"] if callees else [])
        step = "(first | " + " | ".join(alts + ["(rd_split <;> (try rd_step))"]) + ")"
        return ltext + f"""
set_option maxHeartbeats 4000000 in
set_option maxRecDepth 8192 in
theorem {name_run} (gfp : Footprint) (h : Heap) {binders}{hw} (k : Nat) :
      ResultMatches gfp {fp} h {vs} (fun (r : {rt}) h' v => {exp})
        (interp (Scope.env sha) (k + {fuel}) Scope.Id.«{name}» {vs} h)
        ({fname} {rargs}) := by
{inv}{split}  all_goals (
  rw [interp, callName, callValue.eq_def]
  simp [rd_simp, lookup_lit, unfold_known, fieldIndex_lit, stop_call, stop_call_post, {", ".join(defs)}{", *" if hys else ""}]
  rd_step
  repeat' {step}
  all_goals (first | rd_finish | ((try rd_heap); rd_frame; done)))

theorem {name_valid} (gfp : Footprint) (h : Heap) {binders}{hw} :
    ∃ N, ∀ fuel ≥ N,
      ResultMatches gfp {fp} h {vs} (fun (r : {rt}) h' v => {exp})
        (interp (Scope.env sha) fuel Scope.Id.«{name}» {vs} h)
        ({fname} {rargs}) :=
  ⟨{fuel}, fun fuel hf => by
    {"obtain ⟨k, hk⟩ := Nat.exists_eq_add_of_le' hf" if lnames else "obtain ⟨k, rfl⟩ := Nat.exists_eq_add_of_le' hf"}{f"""
    rw [show fuel = k + {fuel} by omega]""" if lnames else ""}
    exact {name_run} sha gfp h {names} k⟩
"""


MEM = "4G"


def check(name, text, workdir, header):
    """Compile one candidate. Returns (name, ok, seconds, first error line)."""
    f = Path(workdir) / f"{name}.lean"
    f.write_text(header + PRELUDE + text + FOOTER)
    t0 = time.time()
    try:
        # Each check runs in its own memory cap: a proof term that blows up must fail, not
        # take the machine down.
        r = subprocess.run(["systemd-run", "--user", "--scope", "-q", "-p", f"MemoryMax={MEM}",
                            "-p", "MemorySwapMax=0", "lake", "env", "lean", str(f)], cwd=ROOT,
                           capture_output=True, text=True, timeout=600)
        out = r.stdout + r.stderr
        ok = r.returncode == 0 and "error" not in out and "sorry" not in out
    except subprocess.TimeoutExpired:
        out, ok = "timeout", False
    err = next((ln.split(".lean:", 1)[-1] for ln in out.splitlines() if "error" in ln), out[:200])
    return name, ok, time.time() - t0, err


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--rev", default="889a389f9")
    ap.add_argument("--preset", default="minimal")
    ap.add_argument("--tier", default="leaves", choices=["leaves", "calls", "loops"])
    ap.add_argument("--only", default=None)
    ap.add_argument("--jobs", type=int, default=2)
    ap.add_argument("--out", default=None)
    ap.add_argument("--emit", default=None, help="write the candidate of one function to --out "
                    "and stop (for work on the tactic)")
    args = ap.parse_args()
    commit, spec_object, sources, spec, fns, sources_text, _ = S.load_scope(
        args.rev, "gloas", args.preset, translate.scope_roots())
    names = T.Names(spec)
    b = translate.Build(spec, fns, names)
    b.sources, b.sources_text, b.config_vars = sources, sources_text, spec_object.config_vars
    em = rd_emit.Emitter(b)
    em.collect()
    em.emit_constants()
    em.emit_config()
    em.build_sigs()
    cls = classify(fns)
    gen_dir = ROOT / "SpecLean/Validation/Gen"
    if args.tier == "leaves":
        tier = sorted(n for n, c in cls.items() if not c["loops"] and not c["calls"])
    else:
        # Functions with calls and no loops. A round checks the ones whose callees all have a
        # theorem; the next round can use the theorems of this one.
        tier = sorted(n for n, c in cls.items() if not c["loops"] and c["calls"])
        have = set(re.findall(r"^theorem (\w+)_run ", (gen_dir / "Leaves.lean").read_text(),
                              re.M))
        if args.tier == "loops":
            tier = sorted(n for n, c in cls.items() if c["loops"])
            have |= set(re.findall(r"^theorem (\w+)_run ", (gen_dir / "Calls.lean").read_text(),
                                   re.M))
    if args.only:
        tier = [n for n in tier if n in args.only.split(",")]
    g = Gen(b, em)
    g.cls, g.slice_memo = cls, {}
    g.readable = (ROOT / "SpecLean/Gen/Readable.lean").read_text()
    from footprint import footprint
    ssz_names = {x for x in dir(spec) if isinstance(getattr(spec, x), type)
                 and T.of_class(getattr(spec, x)) is not None}
    _, _, g.per_fn = footprint(b.fns, ssz_names, lambda t, st: True)
    # The list item classes of the state, and the classes that they hold.
    items = []

    def add_item(c):
        if not T.is_container_cls(c) or c in items:
            return
        for _, ft in c._FIELD_TYPES:
            add_item(ft)
            li = T.list_info(ft)
            if li:
                add_item(li[1])
        items.append(c)
    for c in b.order:
        if T.is_container_cls(c):
            for _, ft in c._FIELD_TYPES:
                li = T.list_info(ft)
                if li and T.is_container_cls(li[1]):
                    add_item(li[1])
    local = LOCAL_HEADER + "".join(
        f"instance : LocalDec dec_{names.cls(c)} := by rd_local dec_{names.cls(c)}\n"
        for c in items) + "\nend SpecLean.Validation.Gen\n"
    lp = ROOT / "SpecLean/Validation/Gen/Local.lean"
    lp.parent.mkdir(parents=True, exist_ok=True)
    if not lp.exists() or lp.read_text() != local:
        lp.write_text(local)
    global PRELUDE
    decs_all = [f"dec_{names.cls(c)}" for c in b.order
                if T.is_uint_cls(c) or T.is_bytesn_cls(c) or T.is_container_cls(c)]
    PRELUDE += "\nattribute [local rd_dec] " + " ".join(decs_all) + "\n"
    # The scalar encoders: a callee's result value is one, and the caller computes with it.
    encs_all = [f"enc_{names.cls(c)}" for c in b.order if T.is_uint_cls(c) or T.is_bytesn_cls(c)]
    PRELUDE += ("\nattribute [local rd_simp] encUint encBytesN encBoolean " + " ".join(encs_all) +
                "\n")
    if args.emit:
        n = args.emit
        text = g.theorem(n, em.sigs[n], fns[n], [], 64)
        Path(args.out).write_text(CALLS_NEXT_HEADER + PRELUDE + text + FOOTER)
        return
    base = {"leaves": "SpecLean.Validation.Gen.Local", "calls": "SpecLean.Validation.Gen.Leaves",
            "loops": "SpecLean.Validation.Gen.Calls"}[args.tier]
    r = subprocess.run(["systemd-run", "--user", "--scope", "-q", "-p", "MemoryMax=8G", "-p",
                        "MemorySwapMax=0", "lake", "build", base], cwd=ROOT,
                       capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit("lake build failed:\n" + r.stdout[-3000:])
    work = tempfile.mkdtemp(prefix="gen-valid-")
    out = Path(args.out) if args.out else gen_dir / (args.tier.capitalize() + ".lean")
    out.parent.mkdir(parents=True, exist_ok=True)
    proved, failed, skipped, secs, body = [], {}, {}, {}, ""

    def doc():
        return (f"\n/-!\n# Validation theorems: {args.tier}\n\nGenerated by tools/gen_valid.py. "
                f"Do not edit. The tactic proves {len(proved)} of the {len(tier)} functions of the "
                f"tier.\n-/\n")
    header = file_header = {"leaves": HEADER, "calls": CALLS_HEADER,
                            "loops": LOOPS_HEADER}[args.tier]
    fuel = {n: 64 for n in (have if args.tier != "leaves" else ())}
    if args.tier == "loops":
        # The fuel of each theorem of the calls tier.
        fuel.update({m[0]: int(m[1]) for m in re.findall(
            r"^theorem (\w+)_run .*?\(k \+ (\d+)\)", (gen_dir / "Calls.lean").read_text(),
            re.M | re.S)})
    todo = list(tier)
    while todo:
        cands = {}
        for n in todo:
            callees = cls[n]["calls"]
            if args.tier != "leaves" and not all(c in fuel for c in callees):
                continue
            f = 64 + max((fuel[c] for c in callees), default=0)
            # The theorems of each callee: the plain one and its class-polymorphic variants.
            lemmas = [k for c in callees for k in fuel if k == c or k.startswith(c + "_p")]
            try:
                cands[n] = (g.theorem(n, em.sigs[n], fns[n], lemmas, f), f)
            except (Unsupported, S.Unsupported, ValueError) as e:
                skipped[n] = f"no statement: {e}"
                continue
            sig = em.sigs[n]
            for j, (_, t) in enumerate(sig.params):
                if t[0] == "uint" and sig.ret[0] == "uint" and not sig.mutated:
                    for tie in (False, True):
                        try:
                            cands[f"{n}_p{j}" + ("i" if tie else "")] = (
                                g.theorem(n, sig, fns[n], lemmas, f, poly=j, tie=tie), f)
                        except (Unsupported, S.Unsupported, ValueError):
                            pass
        todo = [n for n in todo if n not in cands and n not in skipped]
        if not cands:
            break
        with concurrent.futures.ThreadPoolExecutor(args.jobs) as ex:
            results = list(ex.map(lambda kv: check(kv[0], kv[1][0], work, header),
                                  cands.items()))
        new = sorted(n for n, ok, _, _ in results if ok)
        failed.update({n: e for n, ok, _, e in results if not ok and n in tier})
        secs.update({n: round(t, 1) for n, _, t, _ in results})
        proved += [n for n in new if n in tier]
        body += "".join(cands[n][0] for n in new)
        for n in new:
            fuel[n] = cands[n][1]
        out.write_text(f"-- Generated by tools/gen_valid.py. Do not edit.\n{file_header}{doc()}"
                       f"{PRELUDE}{body}{FOOTER}")
        if args.tier == "leaves" or not new:
            break
        # The next round imports the theorems of this one.
        r = subprocess.run(["systemd-run", "--user", "--scope", "-q", "-p", "MemoryMax=8G", "-p",
                            "MemorySwapMax=0", "lake", "build",
                            f"SpecLean.Validation.Gen.{args.tier.capitalize()}"],
                           cwd=ROOT, capture_output=True, text=True)
        if r.returncode != 0:
            sys.exit("lake build of the round failed:\n" + r.stdout[-3000:])
        header = CALLS_NEXT_HEADER if args.tier == "calls" else LOOPS_NEXT_HEADER
    for n in todo:
        skipped.setdefault(n, "a callee has no theorem")
    print(f"tier {args.tier}: {len(proved)}/{len(tier)} proved, wrote {out}")
    print(f"  class-polymorphic variants: "
          f"{sorted(k for k in fuel if k not in tier and re.search(r'_p\d+i?$', k))}")
    for n in sorted(skipped):
        print(f"  SKIP {n}: {skipped[n]}")
    for n in sorted(failed):
        print(f"  FAIL {n} ({secs[n]}s): {failed[n][:160]}")
    for n in proved:
        print(f"  OK {n} ({secs[n]}s)")
    json.dump({"proved": proved, "failed": failed, "skipped": skipped, "secs": secs},
              open(Path(work) / "result.json", "w"), indent=1)
    print(f"candidates in {work}")


if __name__ == "__main__":
    main()
